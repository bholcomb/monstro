#!/usr/bin/env python3
"""Regenerate the C API mirror and ABI probe from Monstro's public headers.

This deliberately accepts only the declarations used by these headers. Unknown
types/declarations fail rather than silently producing an incomplete binding.
Requires Python 3 and a C compiler for preprocessing; normal .NET builds do not.
"""

import argparse
import ast
from pathlib import Path
import re
import subprocess


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CALLBACK = "delegate* unmanaged[Cdecl]<IntPtr, float*, int, void>"
PRIMITIVES = {"void": "void", "float": "float", "double": "double", "int": "int",
              "uint32_t": "uint", "uint64_t": "ulong", "uint8_t": "byte",
              "size_t": "nuint", "char": "byte", "_Bool": "byte",
              "MonstroIconId": "uint"}
KEYWORDS = set("event params object string internal public private ref out in base default checked fixed new operator readonly return lock value is as namespace null".split())


def ident(name):
    return "@" + name if name in KEYWORDS else name


def blocks(text):
    result = []
    for match in re.finditer(r"typedef (struct|enum) (Monstro\w+)\s*\{", text):
        depth, end = 1, match.end()
        while depth:
            depth += (text[end] == "{") - (text[end] == "}")
            end += 1
        tail = re.match(r"\s*(Monstro\w+)\s*;", text[end:])
        if not tail or tail[1] != match[2]:
            raise ValueError(f"Unsupported typedef: {match[2]}")
        result.append((match[1], match[2], text[match.end():end - 1]))
    return result


def integer(expression, constants):
    node = ast.parse(re.sub(r"\s+", " ", expression.strip()), mode="eval").body
    def visit(item):
        if isinstance(item, ast.Constant) and isinstance(item.value, int):
            return item.value
        if isinstance(item, ast.Name):
            return constants[item.id]
        if isinstance(item, ast.UnaryOp) and isinstance(item.op, ast.USub):
            return -visit(item.operand)
        operations = {ast.LShift: lambda a, b: a << b, ast.BitOr: lambda a, b: a | b,
                      ast.Add: lambda a, b: a + b, ast.Sub: lambda a, b: a - b}
        if isinstance(item, ast.BinOp) and type(item.op) in operations:
            return operations[type(item.op)](visit(item.left), visit(item.right))
        raise ValueError(f"Unsupported enum expression: {expression}")
    return visit(node)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = subprocess.check_output(["cc", "-E", "-P", "-x", "c", "-I", str(ROOT / "include"),
                                    str(ROOT / "include/monstro.h")], text=True)
    declarations = blocks(text)
    known = {name for _, name, _ in declarations}
    opaque = set(re.findall(r"typedef struct (Monstro\w+) \1\s*;", text))

    def ctype(c, *, parameter=False):
        c = re.sub(r"\s+", " ", c.strip())
        if c == "MonstroCustomDrawCallback":
            return CALLBACK
        if parameter and c == "const char*":
            return "[MarshalAs(UnmanagedType.LPUTF8Str)] string?"
        stars = c.count("*")
        base = re.sub(r"\bconst\b|\*", "", c).strip()
        if base in opaque:
            # A typed handle struct stands for the pointer to an opaque type.
            if stars != 1:
                raise ValueError(f"Opaque type must be passed by one pointer: {c}")
            return base
        if base == "_Bool" and parameter and stars == 0:
            return "[MarshalAs(UnmanagedType.U1)] bool"
        mapped = PRIMITIVES.get(base, base if base in known else None)
        if mapped is None:
            raise ValueError(f"Unknown C type: {c}")
        return mapped + "*" * stars

    def fields(body):
        for declaration in body.split(";"):
            declaration = declaration.strip()
            if not declaration:
                continue
            match = re.fullmatch(r"(.+?)\s+(\w+(?:\s*\[\d+\])?(?:\s*,\s*\w+)*)", declaration)
            if not match:
                # C often spells pointers next to the field name.
                match = re.fullmatch(r"(.+?\*)\s*(\w+)", declaration)
            if not match:
                raise ValueError(f"Unsupported field: {declaration}")
            for name in match[2].split(","):
                name = name.strip()
                array = re.fullmatch(r"(\w+)\[(\d+)\]", name)
                typ = ctype(match[1])
                if array and typ.endswith("*"):
                    # C# fixed buffers cannot hold pointers; the binding targets 64-bit platforms.
                    typ = "ulong"
                yield typ, array[1] if array else name, int(array[2]) if array else None

    header = "// Generated by bindings/csharp/generate.py from include/monstro/*.h.\n// Do not edit by hand.\n\nusing System;\nusing System.Runtime.InteropServices;\n\nnamespace Monstro;\n\n"
    types, aliases, constants, probe = [], [], {}, ["// Generated ABI checks, compiled against the real C headers.\n#include <monstro.h>\n#include <stddef.h>\n#include <string.h>\n"]
    size_cases, offset_cases, constant_cases = [], [], []
    for name in sorted(opaque):
        size_cases.append(f'    if (!strcmp(name, "{name}")) return sizeof({name} *);')
        offset_cases.append(f'    if (!strcmp(type, "{name}") && !strcmp(field, "Handle")) return 0;')
        types.append(f"""/// <summary>A native {name}*: a typed handle, never null unless IsNull says so.</summary>
[StructLayout(LayoutKind.Sequential)]
public readonly struct {name} : IEquatable<{name}>
{{
    public readonly IntPtr Handle;
    public {name}(IntPtr handle) => Handle = handle;
    public bool IsNull => Handle == IntPtr.Zero;
    public bool Equals({name} other) => Handle == other.Handle;
    public override bool Equals(object? obj) => obj is {name} other && Equals(other);
    public override int GetHashCode() => Handle.GetHashCode();
    public static bool operator ==({name} a, {name} b) => a.Handle == b.Handle;
    public static bool operator !=({name} a, {name} b) => a.Handle != b.Handle;
}}
""")
    for kind, name, body in declarations:
        size_cases.append(f'    if (!strcmp(name, "{name}")) return sizeof({name});')
        if kind == "enum":
            entries, last = [], -1
            for entry in body.split(","):
                if not entry.strip():
                    continue
                parts = entry.strip().split("=", 1)
                value = integer(parts[1], constants) if len(parts) == 2 else last + 1
                constants[parts[0].strip()] = value
                last = value
                entries.append((parts[0].strip(), value))
            prefix = entries[0][0]
            for key, _ in entries[1:]:
                while not key.startswith(prefix):
                    prefix = prefix[:-1]
            prefix = prefix[:prefix.rfind("_") + 1]
            types.append(("[Flags]\n" if name.endswith("Flags") or name == "MonstroAlign" else "") + f"public enum {name}\n{{")
            for key, value in entries:
                member = "".join(part.title() for part in key[len(prefix):].split("_"))
                if member[0].isdigit():
                    member = "Key" + member
                types.append(f"    {member} = {value},")
                aliases.append(f"    public const {name} {key} = {name}.{member};")
                constant_cases.append(f'    if (!strcmp(name, "{key}")) return {key};')
            types.append("}\n")
            continue
        union = re.search(r"union\s*\{(.*?)\}\s*(\w+)\s*;", body, re.S)
        if union:
            union_name = name + "Data"
            known.add(union_name)
            size_cases.append(f'    if (!strcmp(name, "{union_name}")) return sizeof((({name}*)0)->{union[2]});')
            types.append(f"[StructLayout(LayoutKind.Explicit)]\npublic unsafe struct {union_name}\n{{")
            for typ, field, length in fields(union[1]):
                if length:
                    raise ValueError("Unsupported array in union")
                types.append(f"    [FieldOffset(0)] public {typ} {ident(field)};")
                offset_cases.append(f'    if (!strcmp(type, "{union_name}") && !strcmp(field, "{field}")) return offsetof({name}, {union[2]}.{field}) - offsetof({name}, {union[2]});')
            types.append("}\n")
            body = body[:union.start()] + f"{union_name} {union[2]};" + body[union.end():]
        types.append(f"[StructLayout(LayoutKind.Sequential)]\npublic unsafe struct {name}\n{{")
        for typ, field, length in fields(body):
            types.append(f"    public fixed {typ} {ident(field)}[{length}];" if length else f"    public {typ} {ident(field)};")
            offset_cases.append(f'    if (!strcmp(type, "{name}") && !strcmp(field, "{field}")) return offsetof({name}, {field});')
        types.append("}\n")

    functions = []
    pattern = r"((?:const\s+)?\w+(?:\s*\*)*)\s+(monstro_\w+)\s*\(([^{};]*)\)\s*;"
    for match in re.finditer(pattern, text):
        ret, name, arguments = match.groups()
        parameters = []
        if arguments.strip() not in ("", "void"):
            for argument in arguments.split(","):
                parameter = re.fullmatch(r"(.+?)(\w+)\s*(\[\])?", argument.strip())
                if not parameter:
                    raise ValueError(f"Unsupported argument: {argument}")
                typ = parameter[1].strip() + ("*" if parameter[3] else "")
                typ = re.sub(r"\s*\*\s*", "*", typ)
                parameters.append(f"{ctype(typ, parameter=True)} {ident(parameter[2])}")
        result = "bool" if ret == "_Bool" else ctype(ret)
        attributes = "    [DllImport(Lib, CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]\n"
        if ret == "_Bool":
            attributes += "    [return: MarshalAs(UnmanagedType.U1)]\n"
        functions.append(attributes + f"    public static extern {result} {name}({', '.join(parameters)});\n")
    # Ensure every external function declaration was understood.
    expected = set(re.findall(r"\b(monstro_\w+)\s*\([^{};]*\)\s*;", text))
    actual = set(re.findall(r"extern \S+ (monstro_\w+)\(", "\n".join(functions)))
    if actual != expected:
        raise ValueError(f"Unparsed functions: {expected - actual}")
    macro_text = (ROOT / "include/monstro/types.h").read_text()
    colors = []
    for name, values in re.findall(r"#define (MONSTRO_COLOR_\w+)\s+\(\(MonstroColor\)\{\s*([^}]+)\}\)", macro_text):
        components = [value.strip() for value in values.split(",")]
        colors.append(f"    public static readonly MonstroColor {name} = new() {{ r = {components[0]}, g = {components[1]}, b = {components[2]}, a = {components[3]} }};")
    native = header + "public static unsafe partial class Native\n{\n    private const string Lib = \"monstro\";\n\n" + "\n".join(aliases + colors) + "\n\n" + "\n".join(functions) + "}\n"
    probe += ["size_t monstro_binding_sizeof(const char *name) {", *size_cases, "    return (size_t)-1;\n}",
              "size_t monstro_binding_offsetof(const char *type, const char *field) {", *offset_cases, "    return (size_t)-1;\n}",
              "int monstro_binding_constant(const char *name) {", *constant_cases, "    return -2147483647;\n}"]
    outputs = {HERE / "Monstro/Native.cs": native, HERE / "Monstro/Types.cs": header + "\n".join(types),
               HERE / "Monstro.Tests/abi.c": "\n".join(probe) + "\n"}
    for path, contents in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != contents:
                raise SystemExit(f"Stale bindings: {path}; run bindings/csharp/generate.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    print(f"{'Checked' if args.check else 'Generated'} {len(functions)} functions, {len(declarations)} types")


if __name__ == "__main__":
    main()
